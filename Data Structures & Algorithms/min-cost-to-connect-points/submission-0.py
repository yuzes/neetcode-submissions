class Solution:
    # minimum spanning tree
    def minCostConnectPoints(self, points: List[List[int]]) -> int:
        N = len(points)
        adj = {i: [] for i in range(N)}
        for i in range(N):
            x1, y1 = points[i]
            for j in range(i + 1, N):
                x2, y2 = points[j]
                dist = abs(x1 - x2) + abs(y1 - y2)
                adj[j].append((dist, i))
                adj[i].append((dist, j))

        res = 0
        visited = set()
        minH = [(0,0)]
        while len(visited) < N:
            cost, i = heapq.heappop(minH)
            if i in visited:
                continue
            res += cost
            visited.add(i)
            for nextCost, nextPoint in adj[i]:
                heapq.heappush(minH, (nextCost, nextPoint))
        return res


    def dist(p1, p2):
        x1, y1 = p1
        x2, y2 = p2
        return abs(x1 - x2) + abs(y1 - y2)
        